  const STORAGE_KEY = 'soullink.lang.v1';

  function getInitialLang() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === 'ru' || saved === 'en') return saved;
    } catch (_) { /* private mode / file origin */ }
    /* Russian-first interface. English stays one tap away in Settings. */
    return 'ru';
  }

  let lang = getInitialLang();

  function t(key, vars) {
    const table = DICT[lang] || DICT.en;
    let value = table[key];
    if (value == null) value = DICT.en[key];
    if (value == null) value = key;
    if (vars) {
      value = value.replace(/\{(\w+)\}/g, function (_, name) {
        return vars[name] != null ? String(vars[name]) : '{' + name + '}';
      });
    }
    return value;
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      const key = el.getAttribute('data-i18n');
      if (key) el.textContent = t(key);
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) el.setAttribute('placeholder', t(key));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      const key = el.getAttribute('data-i18n-title');
      if (key) el.setAttribute('title', t(key));
    });
    document.documentElement.lang = lang;
    document.documentElement.setAttribute('data-lang', lang);
  }

  function setLang(next) {
    if (next !== 'ru' && next !== 'en') return false;
    if (next === lang) return false;
    lang = next;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (_) {}
    apply(document);
    document.dispatchEvent(new CustomEvent('soullink:language', { detail: { lang: lang } }));
    return true;
  }

  window.SL = window.SL || {};
  SL.i18n = {
    t: t,
    apply: apply,
    setLang: setLang,
    get lang() { return lang; },
    get dict() { return DICT; },
    storageKey: STORAGE_KEY
  };
